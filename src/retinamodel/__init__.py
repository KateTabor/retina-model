    # Update passed values:
    for (k, v) in kw.items():
        if k not in default_params:
            raise ValueError(f"keyword {k} not a parameter of retinamodel")
        params_dict[k] = v
    # Make sure everything is the right size:
    n = len(params_dict["wavelength_nm"])
    keys = ["mac_od", "lens_od", "primary_r", "primary_g", "primary_b"]
    for k in keys:
        if len(params_dict[k]) != n:
            raise ValueError(f"{k} has {len(params_dict[k])} entries, expected {n}")
    return params_dict
